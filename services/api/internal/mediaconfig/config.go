package mediaconfig

import (
	"errors"
	"os"
	"path/filepath"
	"strings"

	"example.com/bailiankai/api/internal/store"
)

type Config struct {
	Driver, Root string
	COS          store.COSConfig
}

func Load() (Config, error) {
	c := Config{Driver: strings.TrimSpace(os.Getenv("MEDIA_DRIVER")), Root: os.Getenv("MEDIA_ROOT"), COS: store.COSConfig{
		Bucket: os.Getenv("COS_BUCKET"), Region: os.Getenv("COS_REGION"), Prefix: os.Getenv("COS_PREFIX"),
		SecretID: os.Getenv("COS_SECRET_ID"), SecretKey: os.Getenv("COS_SECRET_KEY"), SessionToken: os.Getenv("COS_SESSION_TOKEN"),
	}}
	if c.Driver == "" {
		c.Driver = "local"
	}
	if c.Root == "" {
		c.Root = "../../.local/private-media"
	}
	if c.COS.Prefix == "" {
		c.COS.Prefix = "private-media"
	}
	if c.Driver == "local" {
		environment := os.Getenv("APP_ENV")
		if environment != "development" && environment != "server" {
			return c, errors.New("local media requires development or a persistent server volume")
		}
		if environment == "server" && !filepath.IsAbs(os.Getenv("MEDIA_ROOT")) {
			return c, errors.New("server MEDIA_ROOT must explicitly name an absolute persistent directory")
		}
		if c.COS.Bucket != "" || c.COS.SecretID != "" || c.COS.SecretKey != "" {
			return c, errors.New("COS is configured but MEDIA_DRIVER is not cos")
		}
	} else if c.Driver == "cos" {
		if _, err := store.NewCOSMedia(c.COS); err != nil {
			return c, err
		}
	} else {
		return c, errors.New("MEDIA_DRIVER must be local or cos")
	}
	return c, nil
}

func (c Config) Open() (store.Media, error) {
	if c.Driver == "cos" {
		return store.NewCOSMedia(c.COS)
	}
	if c.Driver == "local" {
		return store.NewPrivateMedia(c.Root)
	}
	return nil, errors.New("unsupported media driver")
}

// Backup credentials are deliberately independent of the API credentials.
// snapshot is generated by the backup command and is reused only for recovery.
func Backup(primary Config, snapshot string) (Config, error) {
	if len(snapshot) != 41 || !strings.HasPrefix(snapshot, "snapshot-") {
		return Config{}, errors.New("invalid snapshot id")
	}
	for _, c := range snapshot[9:] {
		if !(c >= '0' && c <= '9' || c >= 'a' && c <= 'f') {
			return Config{}, errors.New("invalid snapshot id")
		}
	}
	driver := os.Getenv("MEDIA_BACKUP_DRIVER")
	if driver == "local" && primary.Driver == "local" && os.Getenv("APP_ENV") == "development" {
		root := os.Getenv("MEDIA_BACKUP_ROOT")
		if root == "" {
			return Config{}, errors.New("MEDIA_BACKUP_ROOT is required")
		}
		absRoot, err := filepath.Abs(root)
		if err != nil {
			return Config{}, err
		}
		absPrimary, err := filepath.Abs(primary.Root)
		if err != nil {
			return Config{}, err
		}
		rel, err := filepath.Rel(absPrimary, absRoot)
		if err != nil || rel == "." || !strings.HasPrefix(rel, ".."+string(filepath.Separator)) && rel != ".." {
			return Config{}, errors.New("backup must be outside primary media root")
		}
		destinationRoot := filepath.Join(absRoot, snapshot)
		rel, err = filepath.Rel(absPrimary, destinationRoot)
		if err != nil || rel == "." || !strings.HasPrefix(rel, ".."+string(filepath.Separator)) && rel != ".." {
			return Config{}, errors.New("snapshot must be outside primary media root")
		}
		return Config{Driver: "local", Root: destinationRoot}, nil
	}
	if driver != "cos" {
		return Config{}, errors.New("MEDIA_BACKUP_DRIVER must be cos (local only for local development)")
	}
	c := Config{Driver: "cos", COS: store.COSConfig{
		Bucket: os.Getenv("COS_BACKUP_BUCKET"), Region: os.Getenv("COS_BACKUP_REGION"), Prefix: "media-backups/" + snapshot,
		SecretID: os.Getenv("COS_BACKUP_SECRET_ID"), SecretKey: os.Getenv("COS_BACKUP_SECRET_KEY"), SessionToken: os.Getenv("COS_BACKUP_SESSION_TOKEN"),
	}}
	if c.COS.Bucket == primary.COS.Bucket {
		return c, errors.New("backup requires a separate bucket")
	}
	if _, err := store.NewCOSMedia(c.COS); err != nil {
		return c, err
	}
	return c, nil
}
